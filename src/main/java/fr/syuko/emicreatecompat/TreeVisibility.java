package fr.syuko.emicreatecompat;

/**
 * When the injected category should be shown.
 */
public enum TreeVisibility {
    /**
     * As soon as an EMI recipe tree is active.
     */
    ALWAYS,
    /**
     * Only while EMI's recipe-tree (crafting) view is enabled.
     */
    CRAFTING_MODE_ONLY
}
